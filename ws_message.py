def active_symbols_event(data):
    print("[+] Active symbols to trade now made available...")
    symbols_data = data.get("active_symbols")
    
    if symbols_data:
        active_symbols = []
        for symbol in symbols_data:
            modified_symbol = {
                "abrv_name": symbol["underlying_symbol"],
                "full_name": symbol["underlying_symbol_name"],
                "is_tradeable":  not symbol["is_trading_suspended"],
            }
            active_symbols.append(modified_symbol)
            
        return active_symbols
    print("No active symbol detected!!!")


